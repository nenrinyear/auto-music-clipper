"""Regenerate the nominal M5 correction from the official DS V02 PDF.

Developer tool only: Python 3, numpy, pdfplumber. Pass the downloaded PDF path.
The source PDF is kept outside version control; its SHA-256 is embedded below.
"""
import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
import pdfplumber

pdf = Path(sys.argv[1])
page = pdfplumber.open(pdf).pages[1]
outline = next(c for c in page.curves if c.get('stroking_color') == (0.93, 0.112, 0.142) and c['top'] > 650)
points = []
for segment in outline['path']:
    op = segment[0]
    if op in ['m', 'l']:
        current = np.array(segment[1])
        points.append(current)
    else:
        controls = [np.array(v) for v in segment[1:]]
        if op == 'v':
            controls = [current, *controls]
        a, b, d = controls
        origin = current
        for t in np.linspace(0, 1, 61)[1:]:
            points.append((1-t)**3*origin + 3*(1-t)**2*t*a + 3*(1-t)*t*t*b + t**3*d)
        current = d
points = np.array(points)
anchors = np.array([[20, 326.6106], [100, 380.9485], [1000, 458.004], [10000, 534.8734], [20000, 559.5036]])


def response(frequency):
    x = min(np.interp(math.log10(frequency), np.log10(anchors[:, 0]), anchors[:, 1]), points[:, 0].max() - .25)
    intersections = []
    for a, b in zip(points[:-1], points[1:]):
        if min(a[0], b[0]) <= x <= max(a[0], b[0]) and a[0] != b[0]:
            intersections.append(a[1] + (b[1]-a[1])*(x-a[0])/(b[0]-a[0]))
    return (710.8407 - (min(intersections)+max(intersections))/2) / 1.4202


frequencies = np.geomspace(20, 20000, 121)
reference = response(1000)
raw = np.array([response(f) - reference for f in frequencies])
smoothed = np.convolve(np.pad(raw, (2, 2), mode='edge'), np.array([1, 2, 3, 2, 1])/9, mode='valid')
taper = np.clip(np.log2(frequencies/20)/2, 0, 1) * np.clip(np.log2(20000/frequencies)/math.log2(20000/16000), 0, 1)
target = np.clip(-smoothed*taper, -3, 3)
centers = np.array([40, 80, 160, 500, 1600, 3200, 6400, 10000, 16000.])
qs = np.array([1, 1, 1, 1, 1, 1, 1, 1.3, 1.5])


def coefficients(frequency, q, gain):
    a = 10**(gain/40)
    w = 2*math.pi*frequency/48000
    alpha, cosine = math.sin(w)/(2*q), math.cos(w)
    return np.array([1+alpha*a, -2*cosine, 1-alpha*a, -2*cosine, 1-alpha/a])/(1+alpha/a)


z = np.exp(-2j*np.pi*frequencies/48000)


def curve(gains):
    result = np.zeros(len(z))
    for frequency, q, gain in zip(centers, qs, gains):
        b0, b1, b2, a1, a2 = coefficients(frequency, q, gain)
        result += 20*np.log10(np.abs((b0+b1*z+b2*z*z)/(1+a1*z+a2*z*z)))
    return result


gains = np.zeros(len(centers))
for _ in range(25):
    current = curve(gains)
    jacobian = np.array([(curve(gains+np.eye(len(gains))[i]*.01)-current)/.01 for i in range(len(gains))]).T
    delta = np.linalg.lstsq(np.vstack([jacobian, .1*np.eye(len(gains))]), np.r_[target-current, -.1*gains], rcond=None)[0]
    gains = np.clip(gains+delta, -3, 3)
actual = curve(gains)
assert np.max(np.abs(actual)) <= 3
profile = {
    'id': 'rode-m5-ds-v02-v1',
    'source': {
        'url': 'https://edge.rode.com/pdf/products/48/M5_Matched_pair_DS_V02.pdf',
        'document': 'M5 Matched Pair datasheet DS V02', 'page': 2, 'retrieved': '2026-10-31',
        'sha256': hashlib.sha256(pdf.read_bytes()).hexdigest(),
        'method': 'Center of red vector outline; logarithmic frequency-axis calibration; relative to 1 kHz',
        'measurementConditions': 'The plot does not specify distance, fixture or an individual unit. This is a nominal curve, not individual calibration.',
        'axis': {'frequencyPdfPoints': anchors.tolist(), 'zeroDbY': 710.8407, 'pointsPerDb': 1.4202},
        'response': [[round(float(f), 6), round(float(v), 6)] for f, v in zip(frequencies, raw)],
    },
    'design': {
        'sampleRate': 48000, 'maxCorrectionDb': 3,
        'lowTaperHz': [20, 80], 'highTaperHz': [16000, 20000],
        'smoothing': 'Five log-spaced samples with triangular weights 1,2,3,2,1 (about one third octave)',
        'fitRmsDb': round(float(np.sqrt(np.mean((actual-target)**2))), 6),
        'bands': [{'frequency': float(f), 'q': float(q), 'gainDb': float(g), 'coefficients': coefficients(f, q, g).tolist()}
                  for f, q, g in zip(centers, qs, gains)],
        'curve': [[round(float(f), 6), round(float(t), 6), round(float(v), 6)] for f, t, v in zip(frequencies, target, actual)],
    },
}
output = Path(__file__).resolve().parent.parent / 'public' / 'm5-profile.js'
output.write_text('// Generated by scripts/digitize-m5.py from the official nominal curve.\nexport const M5_PROFILE = '
                  + json.dumps(profile, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'Wrote {output}; fit RMS {profile["design"]["fitRmsDb"]} dB')
